#!/usr/bin/env bash
# Karya design reference: fetch the four OFL font families and embed them
# into ../html/fonts.css so the reference boards render offline with the
# true fonts.
#
# Run on your own Mac terminal (not inside a sandboxed agent session):
#   cd design/reference/fonts && bash fetch-fonts.sh
#
# Options:
#   --embed-only   skip downloading; embed the .ttf files already in this folder
#   --online       restore the online fonts.css (Google Fonts import)
#
# Requirements: curl, python3. Optional: fonttools (pip install fonttools)
# to subset Noto Serif Devanagari to the glyphs of the Devanagari wordmark.
#
# The download paths below follow the google/fonts repository layout
# (ofl/<family>/<File>[axes].ttf). They were NOT verified from the session
# that wrote this script (its network was blocked). The script checks every
# download and stops with instructions if a path is wrong.

set -euo pipefail
cd "$(dirname "$0")"

BASE="https://raw.githubusercontent.com/google/fonts/main/ofl"
FILES=(
  "ebgaramond/EBGaramond[wght].ttf"
  "instrumentsans/InstrumentSans[wdth,wght].ttf"
  "instrumentsans/InstrumentSans-Italic[wdth,wght].ttf"
  "jetbrainsmono/JetBrainsMono[wght].ttf"
  "notoserifdevanagari/NotoSerifDevanagari[wdth,wght].ttf"
)
LICENSES=(
  "ebgaramond/OFL.txt:OFL-EBGaramond.txt"
  "instrumentsans/OFL.txt:OFL-InstrumentSans.txt"
  "jetbrainsmono/OFL.txt:OFL-JetBrainsMono.txt"
  "notoserifdevanagari/OFL.txt:OFL-NotoSerifDevanagari.txt"
)

if [[ "${1:-}" == "--online" ]]; then
  cp fonts.online.css ../html/fonts.css
  echo "Restored the online fonts.css."
  exit 0
fi

if [[ "${1:-}" != "--embed-only" ]]; then
  for path in "${FILES[@]}"; do
    name="$(basename "$path")"
    url="$BASE/$(echo "$path" | sed 's/\[/%5B/g; s/\]/%5D/g')"
    echo "Downloading $name"
    code=$(curl -sS -L -w '%{http_code}' -o "$name.part" "$url" || echo "000")
    if [[ "$code" != "200" ]]; then
      rm -f "$name.part"
      echo
      echo "Download failed (HTTP $code): $url"
      echo "Get the family from https://fonts.google.com (Download family),"
      echo "copy the variable .ttf named '$name' into this folder,"
      echo "then run: bash fetch-fonts.sh --embed-only"
      exit 1
    fi
    mv "$name.part" "$name"
  done
  for pair in "${LICENSES[@]}"; do
    src="${pair%%:*}"; dst="${pair##*:}"
    curl -sS -L -f -o "$dst" "$BASE/$src" || echo "Warning: license file not fetched: $src"
  done
fi

python3 - <<'PY'
import base64, shutil, subprocess, sys
from pathlib import Path

here = Path(".")
word = "कार्य"  # Karya in Devanagari

faces = [
    # file, family, weight range, stretch range, style
    ("EBGaramond[wght].ttf", "EB Garamond", "400 800", None, "normal"),
    ("InstrumentSans[wdth,wght].ttf", "Instrument Sans", "400 700", "75% 100%", "normal"),
    ("InstrumentSans-Italic[wdth,wght].ttf", "Instrument Sans", "400 700", "75% 100%", "italic"),
    ("JetBrainsMono[wght].ttf", "JetBrains Mono", "100 800", None, "normal"),
    ("NotoSerifDevanagari[wdth,wght].ttf", "Noto Serif Devanagari", "100 900", "62.5% 100%", "normal"),
]

missing = [f for f, *_ in faces if not (here / f).exists()]
if missing:
    sys.exit("Missing font files: " + ", ".join(missing))

deva = here / "NotoSerifDevanagari[wdth,wght].ttf"
deva_use = deva
if shutil.which("pyftsubset"):
    out = here / "NotoSerifDevanagari-subset.ttf"
    subprocess.run(["pyftsubset", str(deva), f"--text={word}", f"--output-file={out}",
                    "--layout-features=*"], check=True)
    deva_use = out
    print("Subset Noto Serif Devanagari to the wordmark glyphs.")
else:
    print("fonttools not found: embedding the full Noto Serif Devanagari file (larger fonts.css).")

rules = ["/* Generated by fetch-fonts.sh. Fonts: SIL Open Font License 1.1 (see OFL-*.txt). */"]
for f, family, weight, stretch, style in faces:
    path = deva_use if family == "Noto Serif Devanagari" else here / f
    data = base64.b64encode(path.read_bytes()).decode()
    rule = ["@font-face {", f'  font-family: "{family}";',
            f'  src: url("data:font/ttf;base64,{data}") format("truetype");',
            f"  font-weight: {weight};", f"  font-style: {style};", "  font-display: block;"]
    if stretch:
        rule.append(f"  font-stretch: {stretch};")
    rule.append("}")
    rules.append("\n".join(rule))
Path("../html/fonts.css").write_text("\n".join(rules) + "\n")
print("Wrote ../html/fonts.css with embedded fonts. The boards now render offline.")
PY
